-- Travas da matriz (criadas depois dos padrões acima): o ADMIN não muda, o AUDITOR não recebe ações,
-- ações e telas administrativas não podem ir para outro perfil.
CREATE FUNCTION role_matrix_guard() RETURNS trigger
  LANGUAGE plpgsql SET search_path = bobinas, public AS $$
DECLARE
  r_code text := CASE WHEN TG_OP = 'DELETE' THEN OLD.role_code ELSE NEW.role_code END;
BEGIN
  IF (SELECT locked FROM role WHERE code = r_code) THEN
    RAISE EXCEPTION 'As permissões do perfil % não podem ser alteradas.', r_code;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    IF TG_TABLE_NAME = 'role_action' THEN
      IF r_code = 'AUDITOR' THEN
        RAISE EXCEPTION 'O auditor é somente leitura e não recebe ações.';
      END IF;
      IF (SELECT admin_only FROM app_action WHERE code = NEW.action_code) THEN
        RAISE EXCEPTION 'A ação % é só do administrador.', NEW.action_code;
      END IF;
    ELSIF (SELECT admin_only FROM app_view WHERE code = NEW.view_code) THEN
      RAISE EXCEPTION 'A tela % é só do administrador.', NEW.view_code;
    END IF;
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER role_action_guard BEFORE INSERT OR UPDATE OR DELETE ON role_action FOR EACH ROW EXECUTE FUNCTION role_matrix_guard();
CREATE TRIGGER role_view_guard   BEFORE INSERT OR UPDATE OR DELETE ON role_view   FOR EACH ROW EXECUTE FUNCTION role_matrix_guard();

