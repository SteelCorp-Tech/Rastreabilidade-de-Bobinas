-- =====================================================================================================
-- Rastreabilidade de bobinas de aço — schema PostgreSQL (proposta para o backend futuro)
--
-- Requer PostgreSQL 13 ou mais novo (gen_random_uuid() embutido, colunas GENERATED).
-- Aplicar num banco vazio:   psql -v ON_ERROR_STOP=1 -d <banco> -f db/schema.sql
--
-- Convenções (ver db/README.md):
--   * nomes em inglês e snake_case, os mesmos do código do protótipo (src/domain);
--   * chave interna `id bigint`; chaves de negócio (cub, slitter_lot, nº do certificado) como UNIQUE;
--   * peso numeric(10,1) em kg; espessura numeric(4,2) em mm; largura integer em mm;
--   * datas e horas em timestamptz (UTC), exibidas em America/Sao_Paulo pela aplicação;
--   * nada que dê para derivar fica duplicado: lote, fornecedor e certificado do CUB, contadores
--     de uso e última obra saem das views;
--   * as invariantes do CLAUDE.md 5.2 também valem no banco (CHECK, UNIQUE parcial, FK composta,
--     gatilhos), além do código;
--   * tabelas editáveis têm `version` (trava otimista) e `updated_at`, mantidos por gatilho.
-- =====================================================================================================

