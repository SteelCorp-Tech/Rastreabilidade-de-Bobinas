-- Numeração do CUB: um contador por ano. reserve_cub_seq() reserva um bloco dentro da transação
-- (trava a linha do ano), por isso dois recebimentos simultâneos nunca repetem número e um número
-- já emitido nunca volta, mesmo que o recebimento seja excluído depois.
CREATE TABLE cub_sequence (
  year     smallint PRIMARY KEY CHECK (year BETWEEN 2000 AND 2999),
  last_seq integer NOT NULL CHECK (last_seq >= 0)
);

CREATE FUNCTION reserve_cub_seq(p_year integer, p_count integer) RETURNS integer
  LANGUAGE plpgsql SET search_path = bobinas, public AS $$
DECLARE
  first_seq integer;
BEGIN
  IF p_count IS NULL OR p_count <= 0 THEN
    RAISE EXCEPTION 'A quantidade de CUBs deve ser um inteiro positivo (recebido: %).', p_count;
  END IF;
  INSERT INTO cub_sequence AS s (year, last_seq) VALUES (p_year, p_count)
  ON CONFLICT (year) DO UPDATE SET last_seq = s.last_seq + EXCLUDED.last_seq
  RETURNING s.last_seq - p_count + 1 INTO first_seq;
  RETURN first_seq;                                  -- primeiro sequencial do bloco reservado
END $$;

CREATE TABLE coil (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cub                       text NOT NULL UNIQUE,    -- CUB-AAAA-NNNNN (prefixo e dígitos vêm de config)
  cub_year                  smallint NOT NULL,
  cub_seq                   integer NOT NULL CHECK (cub_seq > 0),
  mother_coil_id            bigint NOT NULL,
  delivery_id               bigint NOT NULL REFERENCES delivery (id) ON DELETE CASCADE,
  material_id               bigint,
  thickness                 numeric(4,2) NOT NULL CHECK (thickness > 0),
  width                     integer NOT NULL CHECK (width > 0),     -- largura da tira
  galvanization             galvanization NOT NULL,
  received_weight           numeric(10,1) NOT NULL CHECK (received_weight > 0),   -- medido na balança
  received_weight_estimated boolean NOT NULL DEFAULT false,         -- só dados antigos (rateio do Excel)
  current_weight            numeric(10,1) NOT NULL CHECK (current_weight >= 0),
  status                    coil_status NOT NULL DEFAULT 'IN_STOCK',
  storage_location          text,
  blocked_at                timestamptz,
  blocked_reason            text,
  fvm_number                text,
  returned_at               timestamptz,
  returned_to               text,
  returned_reason           text,
  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),
  version                   integer NOT NULL DEFAULT 1,
  UNIQUE (cub_year, cub_seq),
  -- o texto do CUB tem de bater com ano e sequencial
  CHECK (CASE WHEN cub ~ '^[A-Z]{2,6}-[0-9]{4}-[0-9]{3,8}$'
              THEN split_part(cub, '-', 2)::integer = cub_year AND split_part(cub, '-', 3)::integer = cub_seq
              ELSE false END),
  CHECK (current_weight <= received_weight),
  CHECK (status <> 'CONSUMED' OR current_weight = 0),
  CHECK (status <> 'RETURNED' OR returned_at IS NOT NULL),
  CHECK (blocked_at IS NULL OR btrim(coalesce(blocked_reason, '')) <> ''),
  -- espessura e galvanização da tira têm de ser as da bobina mãe (CLAUDE.md 9)
  FOREIGN KEY (mother_coil_id, thickness, galvanization) REFERENCES mother_coil (id, thickness, galvanization),
  -- se houver material do catálogo, espessura, largura e galvanização têm de ser as dele
  FOREIGN KEY (material_id, thickness, width, galvanization) REFERENCES material (id, thickness, width, galvanization)
);
CREATE INDEX coil_mother_coil_idx ON coil (mother_coil_id);
CREATE INDEX coil_delivery_idx    ON coil (delivery_id);
CREATE INDEX coil_stock_idx       ON coil (status, material_id);
CREATE TRIGGER coil_touch BEFORE UPDATE ON coil FOR EACH ROW EXECUTE FUNCTION touch_row();

