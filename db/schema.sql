-- Gatilho genérico: a cada UPDATE, carimba updated_at e incrementa version.
-- A aplicação grava com "... WHERE id = $1 AND version = $2"; 0 linhas afetadas = alguém gravou antes.
CREATE FUNCTION touch_row() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  NEW.version := OLD.version + 1;
  RETURN NEW;
END $$;

