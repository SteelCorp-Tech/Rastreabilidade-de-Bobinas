CREATE TABLE coil_use (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coil_id          bigint NOT NULL REFERENCES coil (id),     -- sem CASCADE: CUB com uso não é excluído
  production_order text NOT NULL CHECK (btrim(production_order) <> ''),   -- OP / protocolo
  project_id       bigint NOT NULL REFERENCES project (id),
  machine_id       bigint NOT NULL REFERENCES machine (id),
  weight_before    numeric(10,1) NOT NULL CHECK (weight_before > 0),
  weight_after     numeric(10,1) CHECK (weight_after >= 0),
  scrap_weight     numeric(10,1) NOT NULL DEFAULT 0 CHECK (scrap_weight >= 0),
  consumption      numeric(10,1) GENERATED ALWAYS AS (weight_before - weight_after) STORED,
  outcome          use_outcome,
  label_file_id    uuid REFERENCES file (id),        -- foto da etiqueta da sobra (opcional)
  is_estimated     boolean NOT NULL DEFAULT false,   -- só usos antigos importados
  opened_at        timestamptz NOT NULL DEFAULT now(),
  opened_by        bigint NOT NULL REFERENCES app_user (id),
  closed_at        timestamptz,
  closed_by        bigint REFERENCES app_user (id),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  version          integer NOT NULL DEFAULT 1,
  CHECK (weight_after IS NULL OR weight_after <= weight_before),
  -- aberto: sem fechamento; fechado: tudo preenchido
  CHECK ((closed_at IS NULL AND closed_by IS NULL AND outcome IS NULL AND weight_after IS NULL)
      OR (closed_at IS NOT NULL AND closed_by IS NOT NULL AND outcome IS NOT NULL AND weight_after IS NOT NULL)),
  CHECK (outcome IS NULL OR (outcome = 'CONSUMED') = (weight_after = 0)),
  CHECK (closed_at IS NULL OR closed_at >= opened_at)
);
-- Um CUB só pode ter um uso aberto por vez.
CREATE UNIQUE INDEX coil_use_one_open_uq ON coil_use (coil_id) WHERE closed_at IS NULL;
CREATE INDEX coil_use_coil_idx        ON coil_use (coil_id, opened_at);
CREATE INDEX coil_use_project_idx     ON coil_use (project_id);
CREATE INDEX coil_use_duplicate_idx   ON coil_use (coil_id, production_order, opened_at);   -- alerta de duplicidade
CREATE TRIGGER coil_use_touch BEFORE UPDATE ON coil_use FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Abrir um uso exige o CUB em estoque e sem bloqueio (nem do CUB nem do lote). A aplicação, na mesma
-- transação, insere o uso e depois passa o CUB para IN_USE. Usos antigos importados já fechados passam.
CREATE FUNCTION coil_use_open_guard() RETURNS trigger
  LANGUAGE plpgsql SET search_path = bobinas, public AS $$
DECLARE
  c record;
BEGIN
  IF NEW.closed_at IS NOT NULL THEN
    RETURN NEW;
  END IF;
  SELECT co.cub, co.status, co.blocked_at, co.blocked_reason, mc.slitter_lot,
         mc.blocked_at AS lot_blocked_at, mc.blocked_reason AS lot_blocked_reason
    INTO c
    FROM coil co JOIN mother_coil mc ON mc.id = co.mother_coil_id
   WHERE co.id = NEW.coil_id
     FOR UPDATE OF co;
  IF c.status <> 'IN_STOCK' THEN
    RAISE EXCEPTION 'O % não está em estoque (situação %).', c.cub, c.status;
  END IF;
  IF c.blocked_at IS NOT NULL THEN
    RAISE EXCEPTION 'O % está bloqueado: %.', c.cub, c.blocked_reason;
  END IF;
  IF c.lot_blocked_at IS NOT NULL THEN
    RAISE EXCEPTION 'O lote % está bloqueado: %.', c.slitter_lot, c.lot_blocked_reason;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER coil_use_open_guard BEFORE INSERT ON coil_use FOR EACH ROW EXECUTE FUNCTION coil_use_open_guard();

