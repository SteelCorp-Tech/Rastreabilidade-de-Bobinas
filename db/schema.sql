-- Estoque de CUBs com tudo o que as telas mostram. display_status = 'BLOCKED' quando o CUB ou o lote
-- está bloqueado (mesma leitura que o protótipo faz hoje).
CREATE VIEW coil_stock AS
SELECT c.id,
       c.cub,
       c.status,
       CASE WHEN c.blocked_at IS NOT NULL OR mc.blocked_at IS NOT NULL THEN 'BLOCKED' ELSE c.status::text END AS display_status,
       (c.blocked_at IS NOT NULL OR mc.blocked_at IS NOT NULL) AS is_blocked,
       coalesce(c.blocked_reason, mc.blocked_reason)              AS block_reason,
       mc.id                                                      AS mother_coil_id,
       mc.slitter_lot,
       s.name                                                     AS supplier,
       cert.number                                                AS certificate_number,
       d.slitter_invoice_number,
       d.received_date,
       c.thickness, c.width, c.galvanization,
       m.erp_code,
       c.received_weight, c.received_weight_estimated, c.current_weight,
       c.storage_location,
       coalesce(c.fvm_number, d.fvm_number)                       AS fvm_number,
       u.use_count,
       u.cumulative_consumption,
       lu.project                                                 AS last_project,
       lu.production_order                                        AS last_production_order
  FROM coil c
  JOIN mother_coil mc      ON mc.id = c.mother_coil_id
  JOIN supplier s          ON s.id = mc.supplier_id
  JOIN delivery d          ON d.id = c.delivery_id
  LEFT JOIN certificate cert ON cert.id = mc.certificate_id
  LEFT JOIN material m     ON m.id = c.material_id
  LEFT JOIN LATERAL (
        SELECT count(*)::integer AS use_count, coalesce(sum(cu.consumption), 0) AS cumulative_consumption
          FROM coil_use cu WHERE cu.coil_id = c.id) u ON true
  LEFT JOIN LATERAL (
        SELECT p.name AS project, cu.production_order
          FROM coil_use cu JOIN project p ON p.id = cu.project_id
         WHERE cu.coil_id = c.id
         ORDER BY cu.opened_at DESC
         LIMIT 1) lu ON true;

-- Saldo por código ERP (tela Estoque, aba "Saldo por código ERP").
CREATE VIEW stock_by_material AS
SELECT erp_code,
       thickness,
       galvanization,
       count(*) FILTER (WHERE status = 'IN_STOCK' AND NOT is_blocked)                         AS available_count,
       coalesce(sum(current_weight) FILTER (WHERE status = 'IN_STOCK' AND NOT is_blocked), 0) AS available_weight,
       count(*) FILTER (WHERE is_blocked)                                                     AS blocked_count,
       count(*) FILTER (WHERE status = 'IN_USE')                                              AS in_use_count
  FROM coil_stock
 WHERE status IN ('IN_STOCK', 'IN_USE') AND erp_code IS NOT NULL
 GROUP BY erp_code, thickness, galvanization;

-- Balanço de massa por lote: líquido da mãe contra CUBs recebidos + refilo do plano vigente
-- (mesma conta de src/domain/massBalance.js).
CREATE VIEW mother_coil_balance AS
SELECT b.*,
       b.net_weight - b.accounted_weight                                   AS difference,
       round(abs(b.net_weight - b.accounted_weight) / b.net_weight * 100, 2) AS difference_pct,
       CASE WHEN b.coil_count = 0 THEN NULL
            ELSE abs(b.net_weight - b.accounted_weight) / b.net_weight * 100 <= b.tolerance_pct END AS within_tolerance
  FROM (
        SELECT mc.id                                AS mother_coil_id,
               mc.slitter_lot,
               mc.net_weight,
               r.coil_count,
               r.received_weight,
               p.trim_weight,
               (p.id IS NOT NULL)                   AS trim_known,
               r.received_weight + coalesce(p.trim_weight, 0) AS accounted_weight,
               cfg.mass_tolerance_pct               AS tolerance_pct
          FROM mother_coil mc
          CROSS JOIN config cfg
          LEFT JOIN LATERAL (
                SELECT count(*)::integer AS coil_count, coalesce(sum(c.received_weight), 0) AS received_weight
                  FROM coil c WHERE c.mother_coil_id = mc.id) r ON true
          LEFT JOIN cutting_plan p ON p.mother_coil_id = mc.id AND p.status <> 'SUPERSEDED'
       ) b;

-- Recall: quem consumiu o aço de cada lote / certificado.
CREATE VIEW lot_consumption AS
SELECT mc.slitter_lot,
       cert.number        AS certificate_number,
       c.cub,
       p.name             AS project,
       cu.production_order,
       mch.name           AS machine,
       cu.opened_at,
       cu.closed_at,
       cu.weight_before,
       cu.weight_after,
       cu.consumption,
       cu.outcome
  FROM coil_use cu
  JOIN coil c          ON c.id = cu.coil_id
  JOIN mother_coil mc  ON mc.id = c.mother_coil_id
  JOIN project p       ON p.id = cu.project_id
  JOIN machine mch     ON mch.id = cu.machine_id
  LEFT JOIN certificate cert ON cert.id = mc.certificate_id;

-- Pendências de certificado: mãe sem certificado ou com certificado sem arquivo.
CREATE VIEW certificate_pending AS
SELECT mc.id AS mother_coil_id,
       mc.slitter_lot,
       s.name  AS supplier,
       cert.number AS certificate_number,
       (cert.id IS NULL)      AS missing_number,
       (cert.file_id IS NULL) AS missing_file
  FROM mother_coil mc
  JOIN supplier s ON s.id = mc.supplier_id
  LEFT JOIN certificate cert ON cert.id = mc.certificate_id
 WHERE cert.id IS NULL OR cert.file_id IS NULL;

